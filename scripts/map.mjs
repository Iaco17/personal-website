// Builds the trip map from real data, once:
//  - coastlines + borders: Natural Earth 1:10m (public domain), in map-data/
//  - road route Lisbon → Madrid → Barcelona → Marseille: OSRM / OpenStreetMap, in map-data/route.json
// Outputs public/map/base.svg (the map itself) and src/data/route-map.js (route path + city positions
// in the same coordinate space, used by the animated overlay).
// Run: node scripts/map.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { geoMercator, geoPath } from 'd3-geo'

const W = 1000
// Wide, roughly square window so the camera can frame the route on portrait phones too
const BOX = { west: -12, east: 10, north: 49, south: 32 }

const projection = geoMercator().scale(1).translate([0, 0])
// Fit longitudes to the width, then shift so the north-west corner is (0, 0)
const [x0, y0] = projection([BOX.west, BOX.north])
const [x1] = projection([BOX.east, BOX.north])
const k = W / (x1 - x0)
projection.scale(k).translate([-x0 * k, -y0 * k])
const H = Math.round(projection([BOX.west, BOX.south])[1])
projection.clipExtent([[0, 0], [W, H]])

const path = geoPath(projection).digits(1)
const read = (f) => JSON.parse(readFileSync(new URL(`../map-data/${f}`, import.meta.url), 'utf8'))

const land = read('land10.geojson')
const borders = read('borders10.geojson')
const osrm = read('route.json').routes[0]

const landD = land.features.map((f) => path(f)).filter(Boolean).join('')
const bordersD = borders.features.map((f) => path(f)).filter(Boolean).join('')

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}">
<rect width="${W}" height="${H}" fill="#0e1626"/>
<path d="${landD}" fill="#1e2836" stroke="#33445a" stroke-width="1.2" stroke-linejoin="round"/>
<path d="${bordersD}" fill="none" stroke="#56677e" stroke-width="1" stroke-dasharray="4 3"/>
</svg>
`
mkdirSync(new URL('../public/map/', import.meta.url), { recursive: true })
writeFileSync(new URL('../public/map/base.svg', import.meta.url), svg)

// Route: project, then thin out points closer than 1.2 units (20k points → a few hundred)
const projected = osrm.geometry.coordinates.map((c) => projection(c))
const pts = [projected[0]]
for (const p of projected) {
  const [lx, ly] = pts[pts.length - 1]
  if (Math.hypot(p[0] - lx, p[1] - ly) > 1.2) pts.push(p)
}
pts.push(projected[projected.length - 1])
const routeD = 'M' + pts.map(([x, y]) => `${x.toFixed(1)} ${y.toFixed(1)}`).join('L')

// Where along the drawn line each city is reached (0..1), plus cumulative road km
const cum = [0]
for (let i = 1; i < pts.length; i++) cum.push(cum[i - 1] + Math.hypot(pts[i][0] - pts[i - 1][0], pts[i][1] - pts[i - 1][1]))
const total = cum[cum.length - 1]
const cityDefs = [
  { name: 'Lisbon', lonlat: [-9.1393, 38.7223], label: 'below' },
  { name: 'Madrid', lonlat: [-3.7038, 40.4168], label: 'below' },
  { name: 'Barcelona', lonlat: [2.1734, 41.3851], label: 'right' },
  { name: 'Marseille', lonlat: [5.3698, 43.2965], label: 'above' },
]
let km = 0
const cities = cityDefs.map((c, i) => {
  const [cx, cy] = projection(c.lonlat)
  let best = 0
  pts.forEach(([x, y], j) => {
    if (Math.hypot(x - cx, y - cy) < Math.hypot(pts[best][0] - cx, pts[best][1] - cy)) best = j
  })
  if (i > 0) km += osrm.legs[i - 1].distance / 1000
  return { ...c, x: +cx.toFixed(1), y: +cy.toFixed(1), at: i === 0 ? 0 : i === cityDefs.length - 1 ? 1 : +(cum[best] / total).toFixed(4), km: Math.round(km) }
})

const place = (lonlat) => projection(lonlat).map((v) => +v.toFixed(1))
const labels = {
  countries: [
    { text: 'Portugal', at: place([-8.1, 39.7]) },
    { text: 'Spain', at: place([-4.4, 39.2]) },
    { text: 'France', at: place([2.6, 45.9]) },
    { text: 'Morocco', at: place([-6.2, 33.4]) },
    { text: 'Algeria', at: place([3.2, 34.6]) },
  ],
  seas: [
    { text: 'Atlantic Ocean', at: place([-11, 42.6]) },
    { text: 'Mediterranean Sea', at: place([4.6, 39.4]) },
    { text: 'Bay of Biscay', at: place([-5.2, 45.4]) },
  ],
}

const js = `// Generated by scripts/map.mjs from Natural Earth + OSRM data. Do not edit by hand.
export const routeMap = ${JSON.stringify({ width: W, height: H, route: routeD, totalKm: Math.round(osrm.distance / 1000), cities, labels }, null, 2)}
`
writeFileSync(new URL('../src/data/route-map.js', import.meta.url), js)

console.log(`base.svg ${W}x${H}, ${Math.round(svg.length / 1024)} KB; route ${pts.length} pts, ${Math.round(osrm.distance / 1000)} km`)
console.log(cities.map((c) => `${c.name} at ${c.at} (${c.km} km)`).join(' | '))
